-- เกณฑ์ชั่วโมงทำงานเต็มเวลา เปลี่ยนจากหน่วย "ชม./เดือน" (เช่น 176) เป็น "ชม./วัน" (เช่น 8)
-- แปลงค่าที่ตั้งไว้เดิมให้เป็นชั่วโมงต่อวัน โดยหารด้วยจำนวนวันทำงานโดยประมาณต่อเดือน (22 วัน)
-- เงื่อนไข > 24 กันไม่ให้แปลงซ้ำ (ไม่มีใครทำงานเกิน 24 ชม./วัน) หากรันซ้ำหรือค่าถูกแก้เป็นรายวันแล้ว
update ot_settings
set full_time_threshold_hours = round(full_time_threshold_hours / 22.0, 2)
where id = true and full_time_threshold_hours > 24;
